//! `measureText` widths of words made of several shaping runs match pinned
//! Chromium 147.0.7727.50 bit for bit.
//!
//! Blink keeps each run's width as a float and adds those floats, in the
//! order it inserted the runs while shaping (`ShapeResult::InsertRun`) and in
//! visual order after spacing (`ApplySpacingOrExpansion`). Float addition
//! depends on the order, so the trace covers left-to-right scripts, font
//! fallback inside one left-to-right or right-to-left segment, right-to-left
//! scripts, and letter spacing. The right-to-left spacing words use Hebrew:
//! Blink adds no letter spacing to cursive scripts such as Arabic, which Div
//! does not follow yet.
//!
//! Oracle: `tests/fidelity/fixtures/multi-run-width-v1`, generated by
//! `tools/canvas/generate_multi_run_width_trace.py` and captured by
//! `tools/canvas/capture_canvas_traces.py`. Only `width` is compared here;
//! `chromium_traces` owns the other `TextMetrics` fields.

use std::fs;
use std::path::Path;

use div_canvas::trace;
use serde_json::Value;

fn fixture() -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fidelity/fixtures/multi-run-width-v1")
}

fn bundled_font(file: &str) -> Option<Vec<u8>> {
    if file.contains(['/', '\\']) || file.starts_with('.') {
        return None;
    }
    fs::read(
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../div-text/fonts")
            .join(file),
    )
    .ok()
}

fn width(observation: &Value) -> Option<f64> {
    observation.get("return")?.get("width")?.as_f64()
}

#[test]
fn multi_run_widths_match_chromium() {
    let platform = if cfg!(target_os = "windows") {
        "windows"
    } else if cfg!(target_os = "linux") {
        "linux"
    } else {
        eprintln!("no Chromium oracle for this operating system");
        return;
    };
    let root = fixture();
    let oracle: Value = serde_json::from_str(
        &fs::read_to_string(root.join(format!("chromium-{platform}.json"))).expect("read oracle"),
    )
    .expect("parse oracle");
    assert_eq!(oracle["chromium"], "147.0.7727.50");
    let want = oracle["traces"]["multi-run-width"]["observations"]
        .as_array()
        .expect("observations");
    let source = fs::read_to_string(root.join("traces/multi-run-width.jsonl")).expect("read trace");
    let replay = trace::replay_with_fonts(&source, &bundled_font).expect("replay");
    assert_eq!(replay.observations.len(), want.len());

    let mut compared = 0;
    let mut failures = Vec::new();
    for (index, (got, want)) in replay.observations.iter().zip(want).enumerate() {
        let Some(chromium) = width(want) else {
            continue;
        };
        compared += 1;
        let div = width(got).expect("Div's measureText has a width");
        if div.to_bits() != chromium.to_bits() {
            failures.push(format!("#{index}: Div {div}, Chromium {chromium}"));
        }
    }
    assert!(compared >= 500, "only {compared} widths compared");
    assert!(
        failures.is_empty(),
        "{} of {compared} widths differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
}
