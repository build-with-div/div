//! `measureText` widths of words made of several shaping runs match pinned
//! Chromium 147.0.7727.50 bit for bit.
//!
//! Blink keeps each run's width as a float and adds those floats, in the
//! order it inserted the runs while shaping (`ShapeResult::InsertRun`) and in
//! visual order after spacing (`ApplySpacingOrExpansion`). Float addition
//! depends on the order, so the trace covers left-to-right scripts, font
//! fallback inside one left-to-right or right-to-left segment, right-to-left
//! scripts, and letter spacing.
//!
//! Two named gaps are replayed and pinned here, so a change to either fails:
//!
//! - Blink adds no letter spacing to cursive scripts (`IsCursiveScript` in
//!   `shape_result.cc`, `ShapeResultSpacing::ComputeSpacing`). Div adds it, so
//!   every width of an Arabic word with letter spacing differs.
//! - Div paints right-to-left words with font fallback differently from
//!   Chromium when the word's runs are not symmetric.
//!
//! Oracle: `tests/fidelity/fixtures/multi-run-width-v1`, generated by
//! `tools/canvas/generate_multi_run_width_trace.py` and captured by
//! `tools/canvas/capture_canvas_traces.py`. Only `width` and the gap canvases
//! are compared here; `chromium_traces` owns the other `TextMetrics` fields.

use std::fs;
use std::path::Path;

use div_canvas::trace;
use serde_json::Value;

/// Widths of Arabic words with letter spacing: four spacings, two sizes,
/// fourteen words. Owner: engine, the cursive letter-spacing repair.
const CURSIVE_SPACING_WIDTHS: usize = 112;

/// Canvases of `rtl-fallback-paint` that differ from Chromium, with the
/// differing pixel count on each platform. Every other canvas must match.
/// Owner: engine, the right-to-left fallback paint repair.
const RTL_FALLBACK_PAINT_GAP: &[(&str, &str, usize)] = &[
    ("linux", "alternating", 3514),
    ("linux", "box-letter", 1443),
    ("linux", "letter-box", 1443),
    ("linux", "letter-box-letter", 717),
];

fn fixture() -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fidelity/fixtures/multi-run-width-v1")
}

fn platform() -> Option<&'static str> {
    if cfg!(target_os = "windows") {
        Some("windows")
    } else if cfg!(target_os = "linux") {
        Some("linux")
    } else {
        None
    }
}

fn oracle(platform: &str) -> Value {
    let path = fixture().join(format!("chromium-{platform}.json"));
    let oracle: Value =
        serde_json::from_str(&fs::read_to_string(path).expect("read oracle")).expect("parse");
    assert_eq!(oracle["chromium"], "147.0.7727.50");
    oracle
}

fn bundled_font(file: &str) -> Option<Vec<u8>> {
    if file.contains(['/', '\\']) || file.starts_with('.') {
        return None;
    }
    fs::read(
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../div-text/fonts")
            .join(file),
    )
    .ok()
}

fn width(observation: &Value) -> Option<f64> {
    observation.get("return")?.get("width")?.as_f64()
}

/// For each `measureText` of the trace, whether it is an Arabic word with
/// letter spacing.
fn cursive_spacing_rows(source: &str) -> Vec<bool> {
    let mut spacing = "0px".to_owned();
    let mut rows = Vec::new();
    for line in source.lines() {
        let row: Value = serde_json::from_str(line).expect("trace line");
        if row["set"] == "letterSpacing" {
            spacing = row["value"].as_str().expect("letter spacing").to_owned();
        } else if row["call"] == "measureText" {
            let word = row["args"][0].as_str().expect("word");
            rows.push(spacing != "0px" && word.contains('\u{0628}'));
        }
    }
    rows
}

#[test]
fn multi_run_widths_match_chromium() {
    let Some(platform) = platform() else {
        eprintln!("no Chromium oracle for this operating system");
        return;
    };
    let oracle = oracle(platform);
    let want = oracle["traces"]["multi-run-width"]["observations"]
        .as_array()
        .expect("observations");
    let source =
        fs::read_to_string(fixture().join("traces/multi-run-width.jsonl")).expect("read trace");
    let replay = trace::replay_with_fonts(&source, &bundled_font).expect("replay");
    assert_eq!(replay.observations.len(), want.len());
    let gap_rows = cursive_spacing_rows(&source);
    assert_eq!(gap_rows.len(), want.len());

    let mut compared = 0;
    let mut gap_differs = 0;
    let mut failures = Vec::new();
    for (index, (got, want)) in replay.observations.iter().zip(want).enumerate() {
        let Some(chromium) = width(want) else {
            continue;
        };
        let div = width(got).expect("Div's measureText has a width");
        let same = div.to_bits() == chromium.to_bits();
        if gap_rows[index] {
            if same {
                failures.push(format!(
                    "#{index}: now matches Chromium; update CURSIVE_SPACING_WIDTHS"
                ));
            } else {
                gap_differs += 1;
            }
            continue;
        }
        compared += 1;
        if !same {
            failures.push(format!("#{index}: Div {div}, Chromium {chromium}"));
        }
    }
    assert!(compared >= 600, "only {compared} widths compared");
    assert!(
        failures.is_empty(),
        "{} of {compared} widths differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
    assert_eq!(
        gap_differs, CURSIVE_SPACING_WIDTHS,
        "named gap: Arabic widths with letter spacing that differ from Chromium"
    );
}

fn decode_png(path: &Path) -> Vec<u8> {
    let decoder = png::Decoder::new(fs::File::open(path).expect("open oracle PNG"));
    let mut reader = decoder.read_info().expect("read PNG header");
    let mut buf = vec![0; reader.output_buffer_size()];
    let info = reader.next_frame(&mut buf).expect("decode PNG");
    assert_eq!(info.color_type, png::ColorType::Rgba, "{}", path.display());
    assert_eq!(info.bit_depth, png::BitDepth::Eight, "{}", path.display());
    buf.truncate(info.buffer_size());
    buf
}

#[test]
fn gap_rtl_fallback_paint_differs_by_the_pinned_counts() {
    let Some(platform) = platform() else {
        return;
    };
    let source =
        fs::read_to_string(fixture().join("traces/rtl-fallback-paint.jsonl")).expect("read trace");
    let replay = trace::replay_with_fonts(&source, &bundled_font).expect("replay");
    assert_eq!(replay.canvases.len(), 6);
    let mut failures = Vec::new();
    for (id, canvas) in &replay.canvases {
        let png = fixture()
            .join(format!("chromium-{platform}"))
            .join(format!("rtl-fallback-paint.{id}.png"));
        let want = decode_png(&png);
        assert_eq!(want.len(), canvas.rgba.len(), "{id}: size");
        let differing = want
            .chunks(4)
            .zip(canvas.rgba.chunks(4))
            .filter(|(a, b)| a != b)
            .count();
        let pinned = RTL_FALLBACK_PAINT_GAP
            .iter()
            .find(|(p, canvas, _)| *p == platform && canvas == id)
            .map_or(0, |(_, _, count)| *count);
        if differing != pinned {
            failures.push(format!("{id}: {differing} pixels differ, pinned {pinned}"));
        }
    }
    assert!(
        failures.is_empty(),
        "named gap changed on {platform}:\n{}",
        failures.join("\n")
    );
}
