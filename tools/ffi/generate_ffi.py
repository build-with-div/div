#!/usr/bin/env python3
"""Generate the frozen Div v0.2 C ABI from the style and event schemas."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
STYLE_SCHEMA = ROOT / "crates/div-style/property-schema.csv"
EVENT_SCHEMA = ROOT / "crates/div-ffi/event-schema.csv"
HEADER_TEMPLATE = ROOT / "tools/ffi/divui.h.in"
HEADER_OUT = ROOT / "include/divui.h"
RUST_OUT = ROOT / "crates/div-ffi/src/generated.rs"
MAP_OUT = ROOT / "crates/div-ffi/divui.map"
SYMBOLS_OUT = ROOT / "docs/v02/generated/div-ffi-symbols.txt"
LAYOUT_OUT = ROOT / "docs/v02/generated/div-ffi-layout.json"
CHECKSUM_OUT = ROOT / "docs/v02/generated/div-ffi-checksum.txt"


TAG_BY_KIND = {
    "display": 5,
    "position": 5,
    "overflow": 5,
    "length": 1,
    "edges": 6,
    "color": 4,
    "number": 2,
    "integer": 3,
    "flex-direction": 5,
    "flex-wrap": 5,
    "item-alignment": 5,
    "content-alignment": 5,
    "gap": 6,
    "font-family": 6,
    "font-weight": 2,
    "border": 6,
    "corner-radii": 6,
    "cursor": 5,
    "list-style": 5,
    "transform": 6,
    "pointer-events": 5,
    # Typography enums are transported as immutable compound handles. This
    # keeps the C ABI exhaustive as Chromium adds enum keywords while the
    # property ID still enforces the concrete Rust type at application time.
    "enum": 6,
    "compound": 6,
}


def read_rows(path: Path) -> list[dict[str, str]]:
    rows = list(csv.DictReader(path.read_text(encoding="utf-8").splitlines()))
    ids = [int(row["id"]) for row in rows]
    if ids != sorted(ids) or len(ids) != len(set(ids)):
        raise SystemExit(f"schema IDs must be unique and ordered: {path}")
    return rows


def generated_header(events: list[dict[str, str]]) -> bytes:
    event_enum = "\n".join(
        f"  {row['c_name']} = {row['id']}," for row in events
    )
    return HEADER_TEMPLATE.read_text(encoding="utf-8").replace(
        "@EVENT_ENUM@", event_enum
    ).encode()


def generated_rust(
    styles: list[dict[str, str]], events: list[dict[str, str]]
) -> bytes:
    properties = "\n".join(
        f"        {row['id']} => Some(StyleProperty::{row['rust_name']}),"
        for row in styles
    )
    tags = "\n".join(
        f"        StyleProperty::{row['rust_name']} => {TAG_BY_KIND[row['value_kind']]},"
        for row in styles
    )
    event_numbers = [int(row["id"]) for row in events]
    if event_numbers == list(range(event_numbers[0], event_numbers[-1] + 1)):
        event_ids = f"{event_numbers[0]}..={event_numbers[-1]}"
    else:
        event_ids = " | ".join(str(value) for value in event_numbers)
    text = f'''// @generated by tools/ffi/generate_ffi.py; do not edit.

use div_style::StyleProperty;

pub(crate) fn property_from_raw(value: i32) -> Option<StyleProperty> {{
    match value {{
{properties}
        _ => None,
    }}
}}

pub(crate) fn expected_value_tag(property: StyleProperty) -> u32 {{
    match property {{
{tags}
    }}
}}

pub(crate) fn valid_event_type(value: u32) -> bool {{
    matches!(value, {event_ids})
}}
'''
    return text.encode()


def exported_symbols(header: bytes) -> list[str]:
    text = header.decode()
    symbols = re.findall(r"^(?:uint32_t|size_t|const uint8_t\*|DivUiStatus)\s+(divui_[a-z0-9_]+)\s*\(", text, re.MULTILINE)
    if len(symbols) != len(set(symbols)):
        raise SystemExit("duplicate exported symbol declaration")
    return sorted(symbols)


def outputs() -> dict[Path, bytes]:
    styles = read_rows(STYLE_SCHEMA)
    events = read_rows(EVENT_SCHEMA)
    header = generated_header(events)
    rust = generated_rust(styles, events)
    symbols = exported_symbols(header)
    symbol_text = "".join(f"{symbol}\n" for symbol in symbols).encode()
    version_map = (
        "DIVUI_0.2 {\n  global:\n"
        + "".join(f"    {symbol};\n" for symbol in symbols)
        + "  local: *;\n};\n"
    ).encode()
    layouts = {
        "abi_version": "0x00020000",
        "pointer_width": 64,
        "types": {
            "DivUiUtf8": {"size": 16, "align": 8},
            "DivUiLength": {"size": 8, "align": 4},
            "DivUiRadiusAxisLengthV1": {"size": 24, "align": 4},
            "DivUiColor": {"size": 4, "align": 1},
            "DivUiStylePayload": {"size": 8, "align": 8},
            "DivUiStyleValue": {"size": 16, "align": 8},
            "DivUiAppConfig": {"size": 40, "align": 8},
            "DivUiAppRunConfig": {"size": 32, "align": 8},
            "DivUiPlatformEvent": {"size": 152, "align": 8},
            "DivUiViewportMetrics": {"size": 40, "align": 8},
            "DivUiDocumentConfig": {"size": 48, "align": 8},
            "DivUiScrollMetricsV1": {"size": 40, "align": 8},
            "DivUiScrollButtonStateV1": {"size": 56, "align": 8},
            "DivUiEditCommandV1": {"size": 32, "align": 4},
            "DivUiFontUnicodeRange": {"size": 8, "align": 4},
            "DivUiFontFeatureDefault": {"size": 8, "align": 4},
            "DivUiFontFaceDescriptor": {"size": 112, "align": 8},
            "DivUiFontFaceInfo": {"size": 152, "align": 8},
            "DivUiRect": {"size": 16, "align": 4},
            "DivUiBitmap": {"size": 32, "align": 8},
            "DivUiTransformOperation": {"size": 48, "align": 4},
            "DivUiEasing": {"size": 48, "align": 8},
            "DivUiLinearStopV1": {"size": 16, "align": 8},
            "DivUiEasingCurveV1": {"size": 80, "align": 8},
            "DivUiAnimationOptionsV1": {"size": 64, "align": 8},
            "DivUiKeyframeV1": {"size": 40, "align": 8},
            "DivUiAnimationOptions": {"size": 104, "align": 8},
            "DivUiAnimationTimeline": {"size": 40, "align": 8},
            "DivUiKeyframe": {"size": 80, "align": 8},
            "DivUiAnimationState": {"size": 48, "align": 8},
            "DivUiAnimationEvent": {"size": 48, "align": 8},
            "DivUiTimelineLengthV1": {"size": 24, "align": 8},
            "DivUiTimelineRangeOffsetV1": {"size": 32, "align": 8},
            "DivUiAnimationAttachmentRangeV1": {"size": 80, "align": 8},
            "DivUiAnimationTimelineSourceV1": {"size": 80, "align": 8},
            "DivUiTimelineRangeBoundsV1": {"size": 16, "align": 8},
            "DivUiAnimationTimelineSnapshotV1": {"size": 96, "align": 8},
            "DivUiAnimationAttachmentSnapshotV1": {"size": 248, "align": 8},
            "DivUiEvent": {"size": 88, "align": 8},
            "DivUiFocusEventInfoV1": {"size": 24, "align": 8},
            "DivUiInputEventInfoV1": {"size": 40, "align": 8},
            "DivUiEventPropertiesV1": {"size": 16, "align": 4},
            "DivUiAccessibilityUpdate": {"size": 40, "align": 8},
            "DivUiAccessibilitySnapshotInfo": {"size": 56, "align": 8},
            "DivUiAccessibilityNodeInfo": {"size": 120, "align": 8},
            "DivUiAccessibilityNodeState": {"size": 112, "align": 8},
            "DivUiAccessibilityScrollInfoV1": {"size": 64, "align": 8},
            "DivUiErrorInfo": {"size": 24, "align": 8},
        },
    }
    layout = (json.dumps(layouts, indent=2, sort_keys=True) + "\n").encode()
    digest = hashlib.sha256(header + rust + symbol_text + layout).hexdigest()
    checksum = f"sha256:{digest}\n".encode()
    return {
        HEADER_OUT: header,
        RUST_OUT: rust,
        MAP_OUT: version_map,
        SYMBOLS_OUT: symbol_text,
        LAYOUT_OUT: layout,
        CHECKSUM_OUT: checksum,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = outputs()
    if args.check:
        drift = [
            str(path.relative_to(ROOT))
            for path, data in generated.items()
            if not path.is_file() or path.read_bytes() != data
        ]
        if drift:
            raise SystemExit("generated FFI drift: " + ", ".join(drift))
        print(f"v0.2 C ABI: artifacts={len(generated)} drift=0")
        return
    for path, data in generated.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(
        f"v0.2 C ABI: properties={len(read_rows(STYLE_SCHEMA))} "
        f"events={len(read_rows(EVENT_SCHEMA))} artifacts={len(generated)}"
    )


if __name__ == "__main__":
    main()
